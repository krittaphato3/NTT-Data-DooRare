import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';
import { resolve, relative, extname } from 'node:path';

const repoRoot = process.cwd();
const aiMaterialRoot = resolve(repoRoot, 'ai-material');
const indexJsonPath = resolve(aiMaterialRoot, '.index.json');
const indexPath = resolve(aiMaterialRoot, 'INDEX.md');
const templatesDir = resolve(aiMaterialRoot, 'templates');

const summaryMaxWords = 12;

function scanDir(dir) {
  const results = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = resolve(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...scanDir(full));
    } else if (extname(entry.name) === '.md') {
      results.push(full);
    }
  }
  return results;
}

function parseFrontmatter(text) {
  const lines = text.split(/\r?\n/);
  const fields = {};
  let i = 0;
  if (lines[0] === '---') {
    i = 1;
    while (i < lines.length) {
      const line = lines[i];
      if (line === '---') {
        i += 1;
        break;
      }
      const sep = line.indexOf(':');
      if (sep > 0) {
        const key = line.slice(0, sep).trim();
        const value = line.slice(sep + 1).trim();
        if (key && Object.prototype.hasOwnProperty.call(fields, key) === false) {
          fields[key] = value;
        }
      }
      i += 1;
    }
  }
  return fields;
}

function firstHeading(text) {
  const match = text.match(/^#{1,6}\s+(.+)$/m);
  return match ? match[1].trim() : null;
}

function firstSentence(text) {
  const cleaned = text.replace(/^---[\s\S]*?---/m, '').trim();
  const lines = cleaned.split('\n').map((line) => line.replace(/^#{1,6}\s+/, '').trim()).filter((line) => line.length > 0);
  for (const line of lines) {
    const match = line.match(/^(.+?)(\{1,3\}|[\.,;:]|$)/);
    if (match && match[1].trim()) {
      return match[1].replace(/[\.,;]$/, '').trim();
    }
  }
  return lines.find((line) => line.trim()) || '';
}

function truncateSummary(text) {
  const words = text.trim().split(/\s+/);
  if (words.length <= summaryMaxWords) {
    return text.trim();
  }
  return words.slice(0, summaryMaxWords).join(' ') + '…';
}

function dateFromMtime(mtimeMs) {
  const d = new Date(mtimeMs);
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

function isIndexFile(relPath) {
  const name = relPath.split(/[\\\/]/).pop();
  return name === 'INDEX.md' || name === '.index.json';
}

function isTemplateFile(relPath) {
  return relPath.split(/[\\\/]/)[0] === 'templates';
}

/* Skills stay out of the index: `skills/README.md` lists the curated set,
   and indexing every SKILL.md (plus its agent/reference files) would drown
   the index in low-value rows. */
function isSkillFile(relPath) {
  const parts = relPath.split(/[\\\/]/);
  if (parts[0] !== 'skills') return false;
  return !(parts.length === 2 && parts[1] === 'README.md');
}

function isHiddenFile(relPath) {
  return relPath.split(/[\\\/]/).some((part) => part.startsWith('.'));
}

function acceptEntry(relPath) {
  if (!relPath) return false;
  if (isTemplateFile(relPath)) return false;
  if (isSkillFile(relPath)) return false;
  if (isIndexFile(relPath)) return false;
  if (isHiddenFile(relPath)) return false;
  return true;
}

const allMdFiles = scanDir(aiMaterialRoot);
const relPaths = allMdFiles
  .map((fullPath) => relative(aiMaterialRoot, fullPath))
  .filter(acceptEntry);

function loadEntry(relPath) {
  const absolutePath = resolve(aiMaterialRoot, relPath);
  const text = readFileSync(absolutePath, 'utf8');
  const fields = parseFrontmatter(text);
  const title = fields.title || firstHeading(text) || relPath;
  const summaryRaw = fields.summary || firstSentence(text) || title;
  const summary = truncateSummary(summaryRaw);
  const ts = statSync(absolutePath).mtimeMs;
  const fileDate = fields.date || dateFromMtime(ts);
  return {
    path: relPath,
    title,
    summary,
    tags: fields.tags || 'session',
    date: fileDate,
    _date: fileDate,
    _mtime: ts,
  };
}

const entries = relPaths.map(loadEntry).sort((a, b) => {
  if (a._date !== b._date) {
    return a._date > b._date ? -1 : 1;
  }
  return a.path < b.path ? -1 : a.path > b.path ? 1 : 0;
});

const indexJson = entries.map((entry) => ({
  path: entry.path,
  title: entry.title,
  summary: entry.summary,
  tags: entry.tags,
  date: entry.date,
}));

writeFileSync(indexJsonPath, JSON.stringify(indexJson, null, 2) + '\n', 'utf8');

const rows = entries
  .map((entry) => {
    const title = String(entry.title).replace(/[|]/g, '\\|');
    const summary = String(entry.summary).replace(/[|]/g, '\\|');
    const tags = String(entry.tags).replace(/[|]/g, '\\|');
    return `| ${entry.path} | ${title} | ${summary} | ${tags} | ${entry.date} |`;
  })
  .join('\n');

const markdown = [
  '# AI Material Index',
  '',
  'This file is generated by `scripts/ai-index.mjs`.',
  '',
  '| Path | Title | Summary | Tags | Date |',
  '|---|---|---|---|---|',
  rows,
  '',
].join('\n');

writeFileSync(indexPath, markdown, 'utf8');

console.log(`Indexed ${entries.length} markdown files.`);
console.log(`Wrote ${indexJsonPath}`);
console.log(`Wrote ${indexPath}`);
